const {chromium}=require('C:/Users/lucas/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs/promises');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();const requests=[],errors=[],checks=[],httpFailures=[];
 page.on('response',r=>{if(r.status()>=400)httpFailures.push({url:r.url(),status:r.status()});});
 page.on('request',r=>{if(r.method()==='POST')requests.push(r.url());});
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(['warning','error'].includes(m.type()))errors.push(m.text());});
 await page.goto('http://localhost:4173/audiencia',{waitUntil:'networkidle'});
 await page.locator('[data-renderer="ready"]').waitFor();
 const cta=page.getByRole('button',{name:'Mapear lentes profissionais',exact:true});
 const foot=page.locator('.audience-map-footnote');
 checks.push({check:'empty',disabled:await cta.isDisabled(),hint:await foot.innerText()});
 await page.getByLabel('Nome',{exact:true}).fill('QA de formulário');
 checks.push({check:'name-only',disabled:await cta.isDisabled(),hint:await foot.innerText()});
 await page.getByLabel('Papel profissional',{exact:true}).fill('Avaliador de exemplo');
 checks.push({check:'name-role',disabled:await cta.isDisabled(),hint:await foot.innerText()});
 await page.locator('.audience-source-option').first().click();
 checks.push({check:'complete',enabled:await cta.isEnabled(),hint:await foot.innerText()});
 const disclosure=page.locator('.audience-add-source summary');
 await disclosure.focus();await page.keyboard.press('Enter');
 checks.push({check:'disclosure-keyboard-open',open:await page.locator('.audience-add-source').evaluate(e=>e.open),sourceEditable:await page.getByLabel('Texto da fonte',{exact:true}).isEditable()});
 await disclosure.focus();await page.keyboard.press('Enter');
 checks.push({check:'disclosure-keyboard-close',closed:await page.locator('.audience-add-source').evaluate(e=>!e.open)});
 checks.push({check:'lengths',name:await page.getByLabel('Nome',{exact:true}).getAttribute('maxlength'),role:await page.getByLabel('Papel profissional',{exact:true}).getAttribute('maxlength')});
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForTimeout(500);
 checks.push({check:'mobile',metrics:await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,canvas:document.querySelectorAll('canvas').length,reduced:matchMedia('(prefers-reduced-motion: reduce)').matches}))});
 await fs.writeFile('artifacts/qa/page-polish-audiencia-form.json',JSON.stringify({at:new Date().toISOString(),base:'http://localhost:4173',checks,errors,httpFailures,postRequests:requests,limitations:['Eight-source boundary inspected in code only; no materials created','Populated profile citations not present in this isolated context']},null,2));
 console.log(JSON.stringify({checks,errors,httpFailures,postRequests:requests}));await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
